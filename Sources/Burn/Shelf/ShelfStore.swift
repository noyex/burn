import AppKit
import CryptoKit
import Observation

struct ShelfItem: Identifiable, Hashable {
    let url: URL
    let date: Date
    var id: URL { url }
}

/// Keeps every image copied to the clipboard (screenshots taken with "Save to Clipboard")
/// as a PNG in Burn's support directory, newest first.
@MainActor
@Observable
final class ShelfStore {
    static let maxItems = 100
    nonisolated static let directory = URL(fileURLWithPath: UsageStore.supportDir + "/Shelf", isDirectory: true)
    /// Marks pasteboard contents written by Burn itself so they aren't captured again.
    private static let ownType = NSPasteboard.PasteboardType("com.mikolaj.burn.shelf")
    /// Types other apps set on passwords and transient data (nspasteboard.org).
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .fileURL, .string, ownType,
    ]

    private(set) var items: [ShelfItem] = []

    @ObservationIgnored private let settings: Settings
    @ObservationIgnored private let pasteboard = NSPasteboard.general
    @ObservationIgnored private var changeCount: Int
    /// Hash of the newest capture, to skip copying the same image twice in a row.
    @ObservationIgnored private var newest: (url: URL, hash: String)?
    /// Captures run one after another so file names and the duplicate check never race.
    @ObservationIgnored private var captureQueue: Task<Void, Never>?
    @ObservationIgnored private var timers: [Timer] = []

    init(settings: Settings) {
        self.settings = settings
        changeCount = pasteboard.changeCount
    }

    /// `capturing: false` only shows what's saved, without watching the clipboard.
    func start(capturing: Bool = true) {
        try? FileManager.default.createDirectory(at: Self.directory, withIntermediateDirectories: true)
        items = Self.loadItems()
        prune()
        if capturing { schedule(every: 0.5) { [weak self] in self?.poll() } }
        schedule(every: 3600) { [weak self] in self?.prune() }
    }

    private func schedule(every seconds: TimeInterval, _ work: @escaping @MainActor () -> Void) {
        let t = Timer(timeInterval: seconds, repeats: true) { _ in MainActor.assumeIsolated { work() } }
        t.tolerance = seconds * 0.4
        RunLoop.main.add(t, forMode: .common)
        timers.append(t)
    }

    // MARK: Actions

    /// Puts the items on the clipboard as images plus file URLs, so both image and file targets accept them.
    func copy(_ items: [ShelfItem]) {
        let entries: [NSPasteboardItem] = items.compactMap { item in
            guard let data = try? Data(contentsOf: item.url) else { return nil }
            let entry = NSPasteboardItem()
            entry.setData(data, forType: .png)
            entry.setString(item.url.absoluteString, forType: .fileURL)
            entry.setData(Data(), forType: Self.ownType)
            return entry
        }
        guard !entries.isEmpty else { return }
        pasteboard.clearContents()
        pasteboard.writeObjects(entries)
        changeCount = pasteboard.changeCount
    }

    func delete(_ doomed: [ShelfItem]) {
        let ids = Set(doomed.map(\.id))
        for item in doomed { try? FileManager.default.removeItem(at: item.url) }
        items.removeAll { ids.contains($0.id) }
    }

    func clear() { delete(items) }

    /// Drops screenshots past the retention period and beyond `maxItems`.
    func prune() {
        let days = settings.shelfRetentionDays
        let cutoff = days > 0 ? Date.now.addingTimeInterval(-Double(days) * 86400) : .distantPast
        let doomed = items.enumerated().filter { i, item in i >= Self.maxItems || item.date < cutoff }.map(\.element)
        if !doomed.isEmpty { delete(doomed) }
    }

    // MARK: Capture

    private func poll() {
        let count = pasteboard.changeCount
        guard count != changeCount else { return }
        changeCount = count
        let types = Set(pasteboard.types ?? [])
        // Text, files and rich documents often carry an image rendition too; only take plain images.
        guard types.isDisjoint(with: Self.skippedTypes),
              let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) else { return }
        captureQueue = Task { [previous = captureQueue] in
            await previous?.value
            await capture(data)
        }
    }

    private func capture(_ data: Data) async {
        let date = Date.now
        let url = Self.fileURL(for: date)
        // Copying the same image twice in a row (e.g. from a chat) shouldn't add a duplicate.
        let previous = newest.flatMap { $0.url == items.first?.url ? $0.hash : nil }
        let saved = await Task.detached { () -> String? in
            let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            guard hash != previous, let png = Self.pngData(data), (try? png.write(to: url)) != nil else { return nil }
            return hash
        }.value
        guard let hash = saved else { return }
        newest = (url, hash)
        items.insert(ShelfItem(url: url, date: date), at: 0)
        prune()
    }

    nonisolated private static func pngData(_ data: Data) -> Data? {
        if data.starts(with: [0x89, 0x50, 0x4E, 0x47]) { return data }
        return NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
    }

    nonisolated private static func fileURL(for date: Date) -> URL {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        let base = "Screenshot \(f.string(from: date))"
        var url = directory.appendingPathComponent(base + ".png")
        var n = 2
        while FileManager.default.fileExists(atPath: url.path) {
            url = directory.appendingPathComponent("\(base) (\(n)).png")
            n += 1
        }
        return url
    }

    nonisolated private static func loadItems() -> [ShelfItem] {
        let keys: [URLResourceKey] = [.creationDateKey]
        let urls = (try? FileManager.default.contentsOfDirectory(
            at: directory, includingPropertiesForKeys: keys, options: .skipsHiddenFiles)) ?? []
        return urls.filter { $0.pathExtension == "png" }
            .map { ShelfItem(url: $0, date: (try? $0.resourceValues(forKeys: Set(keys)).creationDate) ?? .distantPast) }
            .sorted { $0.date > $1.date }
    }
}
